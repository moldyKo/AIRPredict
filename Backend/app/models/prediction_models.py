from datetime import datetime, timezone

from sqlalchemy import (
    JSON,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
)
from sqlalchemy.orm import relationship

from app.core.database import Base


class AQIPrediction(Base):
    """
    Forecast generated by AIRPredict for a specific
    environmental monitoring station.

    Each record represents one forecast point for one
    future timestamp.
    """

    __tablename__ = "aqi_predictions"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    station_id = Column(
        Integer,
        ForeignKey(
            "environmental_stations.id",
            ondelete="CASCADE",
        ),
        nullable=False,
        index=True,
    )

    # -------------------------------------------------
    # MODEL INFORMATION
    # -------------------------------------------------

    model_name = Column(
        String(100),
        nullable=False,
        index=True,
    )

    model_version = Column(
        String(50),
        nullable=True,
    )

    generated_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
        index=True,
    )

    # Timestamp being predicted.
    target_time = Column(
        DateTime(timezone=True),
        nullable=False,
        index=True,
    )

    # Example: 1, 6, 12, 24, 48, 72.
    horizon_hours = Column(
        Integer,
        nullable=False,
        index=True,
    )

    # -------------------------------------------------
    # FORECAST VALUES
    # -------------------------------------------------

    predicted_aqi = Column(
        Float,
        nullable=True,
    )

    predicted_pm25 = Column(
        Float,
        nullable=True,
    )

    predicted_pm10 = Column(
        Float,
        nullable=True,
    )

    predicted_no2 = Column(
        Float,
        nullable=True,
    )

    predicted_co = Column(
        Float,
        nullable=True,
    )

    predicted_o3 = Column(
        Float,
        nullable=True,
    )

    # -------------------------------------------------
    # UNCERTAINTY
    # -------------------------------------------------

    confidence_score = Column(
        Float,
        nullable=True,
    )

    ci_lower = Column(
        Float,
        nullable=True,
    )

    ci_upper = Column(
        Float,
        nullable=True,
    )

    # Explainable AI information.
    #
    # Example:
    # {
    #     "pm25_lag_1h": 0.34,
    #     "wind_speed": 0.21,
    #     "humidity": 0.15
    # }
    feature_importance = Column(
        JSON,
        nullable=True,
    )

    station = relationship(
        "EnvironmentalStation",
    )

    __table_args__ = (
        Index(
            "idx_pred_station_target",
            "station_id",
            "target_time",
        ),
        Index(
            "idx_pred_station_horizon_generated",
            "station_id",
            "horizon_hours",
            "generated_at",
        ),
    )


class ModelPerformanceLog(Base):
    """
    Stores real evaluation metrics for AIRPredict models.

    These values must come from actual validation/testing.
    They must never be manually invented for the UI.
    """

    __tablename__ = "model_performance_logs"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    model_name = Column(
        String(100),
        nullable=False,
        index=True,
    )

    model_version = Column(
        String(50),
        nullable=True,
    )

    evaluated_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
        index=True,
    )

    horizon_hours = Column(
        Integer,
        nullable=False,
        index=True,
    )

    # -------------------------------------------------
    # MODEL METRICS
    # -------------------------------------------------

    mae = Column(
        Float,
        nullable=False,
    )

    rmse = Column(
        Float,
        nullable=False,
    )

    r2_score = Column(
        Float,
        nullable=False,
    )

    sample_count = Column(
        Integer,
        nullable=False,
    )

    __table_args__ = (
        Index(
            "idx_model_perf_name_horizon_eval",
            "model_name",
            "horizon_hours",
            "evaluated_at",
        ),
    )